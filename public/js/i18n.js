// ─────────────────────────────────────────────
// t() 翻訳関数
// ─────────────────────────────────────────────
function t(key, fallback) {
  const lang = typeof getCurrentLanguage === 'function' ? getCurrentLanguage() : 'ja';
  if (lang === 'ja') return fallback ?? key;
  return I18N.en[key] ?? fallback ?? key;
}

// ─────────────────────────────────────────────
// DOM 一括置換
// ─────────────────────────────────────────────
function applyI18n() {
  const lang = typeof getCurrentLanguage === 'function' ? getCurrentLanguage() : 'ja';
  if (lang === 'ja') return;

  // [data-i18n] 属性: textContent を置換
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = I18N.en[key];
    if (val !== undefined) el.textContent = val;
  });

  // [data-i18n-placeholder] 属性: placeholder を置換
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    const val = I18N.en[key];
    if (val !== undefined) el.placeholder = val;
  });

  // [data-i18n-title] 属性: title を置換
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    const val = I18N.en[key];
    if (val !== undefined) el.title = val;
  });
}
